#!/usr/bin/env node
// Lists every runtime image under assets/ so the game can ask "is there art for this ID?"
// Run after adding, renaming or removing art:   node tools/build-asset-manifest.mjs
// tests/naming.test.cjs fails if the manifest is out of date.
import fs from 'node:fs';
import path from 'node:path';
import {fileURLToPath} from 'node:url';

const root = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const assets = path.join(root, 'assets');
const IMAGE = /\.(webp|png|jpe?g|svg)$/i;

export function listAssets() {
  const out = [];
  (function walk(dir) {
    for (const entry of fs.readdirSync(dir, {withFileTypes: true})) {
      const full = path.join(dir, entry.name);
      if (entry.isDirectory()) {
        if (entry.name !== 'source') walk(full); // source art is kept for re-cutting, never loaded
      } else if (IMAGE.test(entry.name)) {
        out.push(path.relative(assets, full).split(path.sep).join('/'));
      }
    }
  })(assets);
  return out.sort();
}

export function renderManifest(files = listAssets()) {
  return '// Generated by tools/build-asset-manifest.mjs. Do not edit by hand.\n' +
    '// Paths are relative to assets/. The game checks this list before showing optional art.\n' +
    'window.ASSET_FILES = ' + JSON.stringify(files, null, 1) + ';\n';
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = path.join(assets, 'manifest.js');
  fs.writeFileSync(target, renderManifest());
  console.log(`Wrote ${path.relative(root, target)} (${listAssets().length} files)`);
}
