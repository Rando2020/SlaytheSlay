#!/usr/bin/env node
// Writes docs/ID-REGISTRY.md: every hero, enemy, relic, god, status and card ID with the
// exact file path its art must use, and whether that file exists yet.
// Run after changing game data or art:   node tools/build-id-registry.mjs
// tests/naming.test.cjs fails if the registry is out of date.
import fs from 'node:fs';
import path from 'node:path';
import {createRequire} from 'node:module';
import {fileURLToPath} from 'node:url';
import {listAssets} from './build-asset-manifest.mjs';

const require = createRequire(import.meta.url);
const {loadGameData, root} = require('./game-data.cjs');

const RARITY = {'-1': 'special', 0: 'starter', 1: 'common', 2: 'uncommon', 3: 'rare'};
const TYPE = {atk: 'Attack', skl: 'Skill', pow: 'Power', status: 'Status', curse: 'Curse'};
const RELIC_RARITY = {c: 'common', u: 'uncommon', r: 'rare', b: 'boss', s: 'shrine'};

export function cardPool(card) {
  if (card.colorless) return 'shared';
  if (card.t === 'status' || card.t === 'curse') return 'shared';
  return card.h || 'aether';
}

export function renderRegistry(data = loadGameData(), files = new Set(listAssets())) {
  const have = p => files.has(p);
  const mark = p => have(p) ? '✓' : 'missing';
  const code = s => '`' + s + '`';
  const table = (head, rows) => [
    '| ' + head.join(' | ') + ' |',
    '| ' + head.map(() => '---').join(' | ') + ' |',
    ...rows.map(r => '| ' + r.join(' | ') + ' |'),
  ].join('\n');
  const out = [];
  out.push(`# ID registry

Generated by \`node tools/build-id-registry.mjs\` from the tables in \`index.html\`. Do not edit by hand.

Every game object has one **ID**: the code key in \`index.html\`. Its art files use that same ID.
To add art, save it at the path shown and run \`node tools/build-asset-manifest.mjs\`.
"missing" means the game falls back to drawn placeholder art. Naming rules are in [NAMING.md](NAMING.md).
`);

  out.push('## Heroes\n');
  out.push(table(['ID', 'Name', 'Poses (`assets/heroes/<id>/<pose>.webp`)', 'Card back', 'Starter relic'],
    Object.entries(data.HEROES).map(([id, h]) => [
      code(id), h.n,
      data.HERO_POSES.map(p => have(`heroes/${id}/${p}.webp`) ? p : `~~${p}~~ missing`).join(', '),
      mark(`ui/cards/backs/${id}.png`), code(h.relic),
    ])));
  out.push('\nEvery hero needs all five poses: ' + data.HERO_POSES.map(code).join(', ') + '.\n');

  const tier = id => data.BOSSES.includes(id) ? 'boss' : data.ELITE.flat().includes(id) ? 'elite'
    : [...data.EASY, ...data.HARD].flat().includes(id) ? 'normal' : 'unused';
  out.push('## Enemies\n');
  out.push(table(['ID', 'Name', 'Tier', 'Art', 'idle', 'attack', 'hurt', 'Source art prefix'],
    Object.entries(data.EN).map(([id, e]) => {
      const kind = e.rig ? 'rig (`assets/rigs/registry.js`)' : e.img ? 'painted poses' : 'drawn placeholder';
      const idle = e.rig ? 'rig parts' : mark(`enemies/${id}/idle.webp`);
      return [code(id), e.n, tier(id), kind, idle,
        mark(`enemies/${id}/attack.webp`), mark(`enemies/${id}/hurt.webp`), code(`art/source/enemies/${id}-*.png`)];
    })));
  out.push('\nEnemy art lives in `assets/enemies/<id>/` and faces **left**.\n');

  out.push('## Relics\n');
  out.push(table(['ID', 'Name', 'Hero', 'Rarity', 'Icon (`assets/ui/relics/<id>.png`)'],
    Object.entries(data.RELICS).map(([id, r]) => [code(id), r.n, r.h || 'any', RELIC_RARITY[r.r] || 'any', mark(`ui/relics/${id}.png`)])));

  out.push('\n## Gods (Oathbound oaths)\n');
  out.push(table(['ID', 'God', 'Oath', 'HUD icon (`assets/ui/hud/oath-<id>.png`)', 'Sanctum (`assets/ui/sanctums/<id>.png`)'],
    Object.entries(data.GODS).map(([id, g]) => [code(id), g.n, g.oath, mark(`ui/hud/oath-${id}.png`), mark(`ui/sanctums/${id}.png`)])));

  out.push('\n## Statuses\n');
  out.push(table(['ID', 'Name', 'Icon (`assets/ui/hud/status-<id>.png`)'],
    Object.entries(data.STN).map(([id, s]) => [code(id), s[0], have(`ui/hud/status-${id}.png`) ? '✓' : '(text chip)'])));

  out.push('\n## Cards\n');
  out.push('Card art is looked up in order: `assets/ui/cards/art/<heroId>/<cardId>.png`, then `assets/ui/cards/art/shared/<cardId>.png`, then the card type\'s drawn icon. Evolved Oathbound forms share their base card\'s ID.\n');
  const pools = {};
  for (const [id, c] of Object.entries(data.K)) (pools[cardPool(c)] ||= []).push([id, c]);
  const title = {aether: 'The Aetherwright (`aether`)', oath: 'The Oathbound (`oath`)', shared: 'Shared: colorless, status and curse cards (`shared`)'};
  for (const pool of ['aether', 'oath', 'shared']) {
    const rows = pools[pool] || [];
    const done = rows.filter(([id]) => have(`ui/cards/art/${pool}/${id}.png`)).length;
    out.push(`### ${title[pool]}: ${done} of ${rows.length} illustrated\n`);
    out.push(table(['ID', 'Name', 'Type', 'Rarity', 'Art path', ''],
      rows.map(([id, c]) => [code(id), c.n, TYPE[c.t] || c.t, c.colorless ? 'colorless ' + (RARITY[c.r] || '') : RARITY[c.r] || String(c.r),
        code(`ui/cards/art/${pool}/${id}.png`), mark(`ui/cards/art/${pool}/${id}.png`)])));
    out.push('');
  }
  out.push('The Oathbound also starts with the Aetherwright\'s `strike` card; his version of its art is ' +
    code('ui/cards/art/oath/strike.png') + ' (' + mark('ui/cards/art/oath/strike.png') + ').\n');

  out.push('## Old names\n');
  out.push('Older saves and Combat Lab links used these short enemy keys. The game translates them on load; never use them for new work.\n');
  out.push(table(['Old key', 'ID'], Object.entries(data.LEGACY_ENEMY_IDS).map(([a, b]) => [code(a), code(b)])));
  out.push('');
  return out.join('\n');
}

if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const target = path.join(root, 'docs', 'ID-REGISTRY.md');
  fs.writeFileSync(target, renderRegistry());
  console.log('Wrote ' + path.relative(root, target));
}
