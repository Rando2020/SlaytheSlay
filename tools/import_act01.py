"""Rebuild the Act I runtime art from the five unmodified PNGs (Pillow)."""
import hashlib
import json
from pathlib import Path
from PIL import Image, ImageDraw

ROOT = Path(__file__).resolve().parents[1] / "assets/maps/act01"
SOURCE = ROOT / "source"
registry = {}


def export(group, name, image):
    path = ROOT / group / (name + ".webp")
    path.parent.mkdir(exist_ok=True)
    image.save(path, quality=90, method=6)
    registry.setdefault(group, {})[name] = path.relative_to(ROOT).as_posix()


def sprite(image, size=None, hollow=False):
    alpha = image.getchannel("A").point(lambda a: max(0, round((a-5)*255/250)))
    image.putalpha(alpha)
    if size:
        image = image.crop(alpha.getbbox())
        image.thumbnail((size-12, size-12), Image.Resampling.LANCZOS)
        tile = Image.new("RGBA", (size,size))
        tile.alpha_composite(image, ((size-image.width)//2,(size-image.height)//2))
        image = tile
        if hollow:
            ImageDraw.Draw(image).ellipse((68,68,188,188), fill=(0,0,0,0))
    else:
        # Clear the perimeter so unrelated edge pixels cannot bleed during scaling.
        a = image.getchannel("A")
        ImageDraw.Draw(a).rectangle((0,0,image.width-1,image.height-1),outline=0)
        image.putalpha(a)
        image.thumbnail((768,512), Image.Resampling.LANCZOS)
    a = image.getchannel("A")
    assert a.getextrema()[0] == 0 and a.getextrema()[1] > 50
    return image


def grid(filename, group, names, cell, cols):
    sheet = Image.open(SOURCE / filename)
    for i,name in enumerate(names.split()):
        x,y = i%cols*cell,i//cols*cell
        export(group,name,sprite(sheet.crop((x,y,x+cell,y+cell)),256,group=="frames"))


# Irregular boxes measured on 465 x 310 previews of the original sheets.
def regions(group, boxes):
    sheet = Image.open(SOURCE / ("map_"+group+"_atlas.png"))
    for name,box in boxes.items():
        coords = tuple(round(k*(sheet.width/465 if i%2==0 else sheet.height/310))
                       for i,k in enumerate(box))
        export(group,name,sprite(sheet.crop(coords)))


for entry in json.loads((SOURCE/"manifest.json").read_text())["assets"]:
    data = (SOURCE/entry["file"]).read_bytes()
    if hashlib.sha256(data).hexdigest() != entry["sha256"]:
        raise ValueError("Source artwork checksum mismatch: "+entry["file"])
